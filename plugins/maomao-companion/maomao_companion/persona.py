"""One public persona source; no access to host private overlays or user memory."""
import hashlib
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[1]/"persona.md"


def public_persona():
    text=SOURCE.read_text(encoding="utf-8")
    if not text.startswith("<!-- maomao-persona:") or not 200 <= len(text) <= 12000:
        raise ValueError("invalid public persona asset")
    return text


def persona_digest():
    return hashlib.sha256(public_persona().encode()).hexdigest()


